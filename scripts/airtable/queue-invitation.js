const {responseId}=input.config();
const responses=base.getTable('Clinic Staffing Responses');
const response=await responses.selectRecordAsync(responseId);
if(!response||response.getCellValueAsString('Initial Response')!=='No Response')return;
const clinicId=(response.getCellValue('Clinic Date')||[])[0]?.id;
const memberId=(response.getCellValue('Team Member')||[])[0]?.id;
if(!clinicId||!memberId)return;
const clinic=await base.getTable('Clinic Staffing Dates').selectRecordAsync(clinicId);
const member=await base.getTable('Clinic Team Members').selectRecordAsync(memberId);
if(!clinic||!member||['Cancelled','Completed'].includes(clinic.getCellValueAsString('Scheduling Stage'))||!member.getCellValue('Active')||!member.getCellValue('Receive Scheduling Emails'))return;
const date=String(clinic.getCellValue('Clinic Date')||'').slice(0,10);
const role=member.getCellValueAsString('Role');
if(role==='Vet Tech'&&!clinic.getCellValue('Confirmed Veterinarians'))return;
if(role==='Clinic Volunteer'&&(!clinic.getCellValue('Confirmed Veterinarians')||!clinic.getCellValue('Confirmed Vet Techs')))return;
const email=member.getCellValueAsString('Email');
if(!date||!email)return;
const key=clinic.id+'|'+date+'|'+response.id+'|'+clinic.getCellValueAsString('Last Reviewed Schedule')+'|invitation|'+email.toLowerCase();
const queue=base.getTable('Clinic Staffing Notifications');
const existing=await queue.selectRecordsAsync({fields:['Notification Key']});
if(existing.records.some(r=>r.getCellValueAsString('Notification Key')===key))return;
await queue.createRecordAsync({'Notification Key':key,Recipient:email,Subject:'Safe Haven clinic availability: '+date,Message:`Please tell us whether you can attend the clinic on ${date}.\n\nhttps://same-abupp8cny20-latest.netlify.app/portal/clinic`});
